SPAM_STOP_WORDS = [
    "казино", "1win", "крипт", "слив курса", "ставка", "заработок от", "пассивный доход"
]

def classify_order(text: str):
    """
    Возвращает (is_order: bool, category: str, matched_keyword: str)
    Строгая фильтрация: отсекает 100% резюме, оставляя только реальные заказы.
    """
    if not text:
        return False, None, None
        
    text_lower = text.lower()
    
    if any(sw in text_lower for sw in SPAM_STOP_WORDS):
        return False, "SPAM", None
        
    # 1. Отсекаем любые резюме и саморекламу
    for pat in PROMO_PATTERNS:
        if re.search(pat, text_lower):
            return False, "RESUME", None
            
    # 2. Ищем четкий интент заказчика (ищу/ищем/нужен/нужна/нужны/требуется)
    matched_target = None
    for pat in TARGET_SEARCH_PATTERNS:
        m = re.search(pat, text_lower)
        if m:
            matched_target = m.group(0).strip()
            break
            
    if not matched_target:
        return False, "NO_ORDER_INTENT", None
        
    # 3. Отсекаем нецелевые роли (актеры, грим, свет, звук)
    for pat in NON_TARGET_ROLES:
        if re.search(pat, text_lower):
            has_our_search = any(k in text_lower for k in [
                "ищем монтаж", "ищу монтаж", "нужен монтаж",
                "ищем режиссер", "ищу режиссер", "нужен режиссер",
                "ищем оператор", "ищу оператор", "нужен оператор",
                "ищем видеограф", "ищу видеограф", "нужен видеограф",
                "ищу креатор", "ищем креатор", "нужен креатор"
            ])
            if not has_our_search:
                return False, "NON_TARGET_ROLE", None
                
    # Определяем категорию
    if any(k in matched_target for k in ["режисс", "продакшн", "продюсер", "креатор"]):
        category = "🎬 Режиссура и Продакшн"
    elif any(k in matched_target for k in ["монтаж", "рилс", "давинчи", "davinci", "premiere"]):
        category = "✂️ Видеомонтаж и Постпродакшн"
    else:
        category = "🎥 Оператор и Съемка"
        
    return True, category, matched_target
